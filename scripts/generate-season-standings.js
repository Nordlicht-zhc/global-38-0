const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const seasons = Array.from({ length: 32 }, (_, index) => {
  const start = 1994 + index;
  return `${start}-${String(start + 1).slice(-2)}`;
});
const competitions = { eng: "E0", esp: "SP1", ita: "I1", ger: "D1", fra: "F1" };

function csvRows(text) {
  const lines = text.replace(/^\uFEFF/, "").split(/\r?\n/).filter(Boolean);
  const headers = lines.shift().split(",");
  return lines.map((line) => {
    const values = line.split(",");
    return Object.fromEntries(headers.map((header, index) => [header, values[index]]));
  });
}

function calculateTable(rows) {
  const table = new Map();
  const team = (name) => {
    if (!table.has(name)) table.set(name, { name, points: 0, goalDiff: 0, goalsFor: 0, wins: 0 });
    return table.get(name);
  };
  rows.forEach((match) => {
    const homeGoals = Number(match.FTHG);
    const awayGoals = Number(match.FTAG);
    if (!match.HomeTeam || !match.AwayTeam || !Number.isFinite(homeGoals) || !Number.isFinite(awayGoals)) return;
    const home = team(match.HomeTeam);
    const away = team(match.AwayTeam);
    home.goalsFor += homeGoals;
    away.goalsFor += awayGoals;
    home.goalDiff += homeGoals - awayGoals;
    away.goalDiff += awayGoals - homeGoals;
    if (homeGoals > awayGoals) {
      home.points += 3;
      home.wins += 1;
    } else if (homeGoals < awayGoals) {
      away.points += 3;
      away.wins += 1;
    } else {
      home.points += 1;
      away.points += 1;
    }
  });
  return [...table.values()].sort((a, b) => b.points - a.points
    || b.goalDiff - a.goalDiff
    || b.goalsFor - a.goalsFor
    || b.wins - a.wins
    || a.name.localeCompare(b.name));
}

async function main() {
  const standings = {};
  const tasks = [];
  for (const season of seasons) {
    standings[season] = {};
    const codeSeason = `${String(Number(season.slice(2, 4))).padStart(2, "0")}${season.slice(-2)}`;
    for (const [league, code] of Object.entries(competitions)) {
      tasks.push(async () => {
        const url = `https://www.football-data.co.uk/mmz4281/${codeSeason}/${code}.csv`;
        const response = await fetch(url);
        if (!response.ok) throw new Error(`${response.status} ${url}`);
        const table = calculateTable(csvRows(await response.text()));
        standings[season][league] = table.map((row) => row.name);
      });
    }
  }
  let cursor = 0;
  async function worker() {
    while (cursor < tasks.length) {
      const task = tasks[cursor];
      cursor += 1;
      await task();
    }
  }
  await Promise.all(Array.from({ length: 10 }, () => worker()));
  const output = `// Generated by scripts/generate-season-standings.js from football-data.co.uk match results.\nconst HISTORICAL_STANDINGS = ${JSON.stringify(standings, null, 2)};\n`;
  fs.writeFileSync(path.join(root, "src", "season-standings.js"), output);
  console.log(`Generated standings for ${seasons.length} seasons.`);
}

main().catch((error) => {
  console.error(error.message || error);
  process.exitCode = 1;
});
